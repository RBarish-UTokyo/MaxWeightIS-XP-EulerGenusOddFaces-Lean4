"""Generate Challenge.lean from the authoritative project sources.

The body of the single module `WeightedMIS/Statement.lean`, which holds every
definition the main claim uses, is copied verbatim. Comparator checks that every constant used
by the statement is the same kernel declaration in the solution environment,
so a stale or edited copy is rejected rather than trusted.
"""

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "WeightedMIS"

DECL_START = re.compile(
    r"^(@\[[^\]]*\]\s*)?(noncomputable\s+)?(def|abbrev|structure|inductive|theorem|instance)\s+(\S+)")


def declarations(path):
    """Split a file's top level into (name, text) blocks, each with its docstring."""
    lines = path.read_text().splitlines()
    blocks, current, name, pending_doc = [], [], None, []
    in_doc = False
    for line in lines:
        if in_doc:
            pending_doc.append(line)
            if line.rstrip().endswith("-/"):
                in_doc = False
            continue
        if line.startswith("/--"):
            if name is not None:
                blocks.append((name, current))
                name, current = None, []
            pending_doc = [line]
            in_doc = not line.rstrip().endswith("-/")
            continue
        m = DECL_START.match(line)
        if m:
            if name is not None:
                blocks.append((name, current))
            name, current = m.group(4), pending_doc + [line]
            pending_doc = []
            continue
        if name is not None and (line.startswith(" ") or line.startswith("\t") or line == ""):
            current.append(line)
            continue
        if name is not None:
            blocks.append((name, current))
            name, current = None, []
        pending_doc = []
    if name is not None:
        blocks.append((name, current))
    return {n: "\n".join(t).rstrip() + "\n" for n, t in blocks}


def body(path):
    """Everything after the `@[expose] public section` line of a module."""
    text = path.read_text()
    marker = "@[expose] public section\n"
    return text[text.index(marker) + len(marker):].strip() + "\n"


def pick(path, names):
    decls = declarations(path)
    missing = [n for n in names if n not in decls]
    if missing:
        sys.exit(f"missing declarations in {path.name}: {missing}")
    return "\n".join(decls[n] for n in names)


def main():
    statement = body(SRC / "Statement.lean")
    assert statement.rstrip().endswith("end")
    statement = statement.rstrip()[: -len("end")].rstrip() + "\n"

    out = f"""-- GENERATED by scripts/gen_challenge.py from the project sources; do not edit by hand.
module

public import Mathlib

/-!
# Challenge: maximum-weight independent set in embedded graphs

This file is the statement a reader should audit. It states Theorem 1 of
*Maximum-weight independent set in embedded graphs parameterized by Euler
genus and number of odd faces* (forthcoming) for an explicit sixteen-register
pointer machine with a logarithmic bit-cost measure that includes an explicit
stack simulation of recursive calls.

It is a self-contained copy, generated by `scripts/gen_challenge.py`, of the
authoritative module `WeightedMIS/Statement.lean`, followed by the
single target `WeightedMIS.Spec.main_claim`, stated with `sorry`. Comparator
checks that each constant used by the statement is the same kernel declaration
in the solution environment.

Reading order: the machine (cells, events, runs, commands, the interpreter
`FramedExec`, and the cost `stackBitCost`), then the combinatorial surface
model (`Spec`), then the input encoding, output reading and `MainClaim`.
-/

@[expose] public section

{statement}
/-- **Theorem 1** (uniform XP bound in `γ + k` with exponent `D(γ, k) + C`). -/
theorem WeightedMIS.Spec.main_claim : WeightedMIS.Spec.MainClaim := by
  sorry

end
"""
    (ROOT / "Challenge.lean").write_text(out)
    n = out.count("\n")
    print(f"Challenge.lean: {n} lines, {len(out.encode())} bytes")


if __name__ == "__main__":
    main()
